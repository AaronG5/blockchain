struct Category {
   std::string name;
   std::string description;
   std::vector<std::string> inputs;
};

static std::vector<Category> buildCategories() {
   std::mt19937_64 rng(SEED);
   std::vector<Category> cats;

   {
      Category c{"permutations", "All 8! orderings of \"abcdefgh\"", {}};
      std::string s = "abcdefgh";
      do {
         c.inputs.push_back(s);
      } while (std::next_permutation(s.begin(), s.end()));
      cats.push_back(std::move(c));
   }
   {
      Category c{"permutations_repeated", "All distinct orderings of \"aabbccdd\"", {}};
      std::string s = "aabbccdd";
      do {
         c.inputs.push_back(s);
      } while (std::next_permutation(s.begin(), s.end()));
      cats.push_back(std::move(c));
   }
   {
      Category c{"rotations", "All rotations of 20 random strings (lengths 8, 16, ..., 160)", {}};
      for (int k = 1; k <= 20; ++k) {
         std::string s = randomString(rng, 8 * k);
         for (std::size_t r = 0; r < s.size(); ++r) {
            c.inputs.push_back(s);
            std::rotate(s.begin(), s.begin() + 1, s.end());
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"swap_inside_pair",
                 "20 random 64-byte strings, plus each with bytes 2k and 2k+1 swapped (k = 0..31)", {}};
      for (int k = 0; k < 20; ++k) {
         std::string base = randomString(rng, 64);
         c.inputs.push_back(base);
         for (int i = 0; i + 1 < 64; i += 2) {
            std::string v = base;
            std::swap(v[i], v[i + 1]);
            c.inputs.push_back(v);
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"swap_across_pair",
                 "20 random 64-byte strings, plus each with bytes 2k+1 and 2k+2 swapped (k = 0..30)", {}};
      for (int k = 0; k < 20; ++k) {
         std::string base = randomString(rng, 64);
         c.inputs.push_back(base);
         for (int i = 1; i + 1 < 64; i += 2) {
            std::string v = base;
            std::swap(v[i], v[i + 1]);
            c.inputs.push_back(v);
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"repeated_patterns",
                 "Patterns \"a\", \"ab\", \"abc\", \"abcd\", \"0123456789\", \" \" repeated to lengths 1..300", {}};
      for (const std::string p : {"a", "ab", "abc", "abcd", "0123456789", " "}) {
         for (int len = 1; len <= 300; ++len) {
            std::string s;
            while (static_cast<int>(s.size()) < len) s += p;
            s.resize(len);
            c.inputs.push_back(s);
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"short_inputs", "Every 1-byte and 2-byte string over the alphabet", {}};
      for (char x : ALPHABET) c.inputs.push_back(std::string(1, x));
      for (char x : ALPHABET) {
         for (char y : ALPHABET) c.inputs.push_back(std::string{x, y});
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"single_byte_change",
                 "10 random 256-byte strings, plus each with one byte changed to the next alphabet character", {}};
      for (int k = 0; k < 10; ++k) {
         std::string base = randomString(rng, 256);
         c.inputs.push_back(base);
         for (std::size_t i = 0; i < base.size(); ++i) {
            std::string v = base;
            std::size_t pos = ALPHABET.find(v[i]);
            v[i] = ALPHABET[(pos + 1) % ALPHABET.size()];
            c.inputs.push_back(v);
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"same_sum_change",
                 "10 random 64-byte strings, plus each with byte i increased and byte i+1 decreased by 1", {}};
      for (int k = 0; k < 10; ++k) {
         std::string base = randomString(rng, 64);
         c.inputs.push_back(base);
         for (std::size_t i = 0; i + 1 < base.size(); ++i) {
            if (base[i] == '~' || base[i + 1] == ' ') continue;   // keep inside the alphabet
            std::string v = base;
            ++v[i];
            --v[i + 1];
            c.inputs.push_back(v);
         }
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"tail_after_128",
                 "Random 128-byte prefix followed by every ordering of \"abcdef\"", {}};
      std::string prefix = randomString(rng, 128);
      std::string tail = "abcdef";
      do {
         c.inputs.push_back(prefix + tail);
      } while (std::next_permutation(tail.begin(), tail.end()));
      cats.push_back(std::move(c));
   }
   {
      Category c{"zero_padding", "20 random strings (lengths 5..24), each followed by 0..8 NUL bytes", {}};
      for (int k = 0; k < 20; ++k) {
         std::string base = randomString(rng, 5 + k);
         for (int pad = 0; pad <= 8; ++pad) c.inputs.push_back(base + std::string(pad, '\0'));
      }
      cats.push_back(std::move(c));
   }
   {
      Category c{"whitespace", "50 short words with leading, trailing and doubled spaces", {}};
      for (int k = 0; k < 50; ++k) {
         std::string w = randomString(rng, 3 + k % 10);
         for (const std::string v : {w, " " + w, w + " ", " " + w + " ", "  " + w, w + "  "}) {
            c.inputs.push_back(v);
         }
      }
      cats.push_back(std::move(c));
   }

   return cats;
}

// ---------------------------------------------------------------------------------------------

int main(int argc, char* argv[]) {
   fs::path baseDir = (argc > 1) ? fs::path(argv[1]) : fs::absolute(argv[0]).lexically_normal().parent_path();
   int pairs = (argc > 2) ? std::stoi(argv[2]) : DEFAULT_PAIRS;
   fs::path outDir = baseDir / "out";
   fs::create_directories(outDir);

   std::ofstream report(baseDir / "exp2_results.txt");
   report << std::fixed;

   report << "Alphabet: " << ALPHABET.size() << " printable ASCII characters, 0x20 (space) to 0x7E (~), 1 byte each\n";
   report << "Generator: std::mt19937_64, seed " << SEED << " + length (structured tests: seed " << SEED << ")\n";
   report << "Hash size: " << HASH_BITS << " bits (" << HASH_BITS / 4 << " hex characters)\n";
   report << "Pairs per length: " << pairs << " (the two inputs of a pair always differ)\n\n";

   // 1 and 2: random pairs and full set
   report << "=== Random inputs ===\n\n";
   report << std::left << std::setw(8) << "Length" << std::right
          << std::setw(9) << "Pairs" << std::setw(12) << "Pair coll."
          << std::setw(10) << "Inputs" << std::setw(10) << "Distinct"
          << std::setw(10) << "Hashes" << std::setw(12) << "Coll. grps"
          << std::setw(12) << "Coll. pairs" << std::setw(10) << "Time s" << "\n";
   report << std::string(93, '-') << "\n";

   std::vector<RandomResult> results;
   for (int length : LENGTHS) {
      std::cerr << "Random inputs, length " << length << "...\n";
      RandomResult r = runRandom(length, pairs, outDir);
      report << std::left << std::setw(8) << r.length << std::right
             << std::setw(9) << r.pairs << std::setw(12) << r.pairCollisions
             << std::setw(10) << r.full.total << std::setw(10) << r.full.distinctInputs
             << std::setw(10) << r.full.distinctHashes << std::setw(12) << r.full.groups.size()
             << std::setw(12) << r.fullCollidingPairs << std::setw(10) << std::setprecision(2) << r.seconds << "\n";
      results.push_back(std::move(r));
   }
   report << "\nPair coll.:  pairs whose two inputs got the same hash\n"
          << "Distinct:    distinct inputs among all 2 * pairs inputs of that length\n"
          << "Hashes:      distinct hashes among the distinct inputs\n"
          << "Coll. grps:  groups of distinct inputs that share one hash\n"
          << "Coll. pairs: distinct input pairs inside those groups\n"
          << "Examples:    out/pair_collisions_<length>.txt and out/set_collisions_<length>.txt\n\n";

   // Ideal hash comparison
   report << "=== Expected collisions for an ideal hash ===\n\n";
   report << std::left << std::setw(8) << "Length" << std::right
          << std::setw(14) << "Pairwise" << std::setw(14) << "Full set" << "\n";
   report << std::string(36, '-') << "\n";
   for (const auto& r : results) {
      long double m = static_cast<long double>(r.full.distinctInputs);
      long double setPairs = m * (m - 1) / 2;
      report << std::left << std::setw(8) << r.length << std::right << std::scientific << std::setprecision(3)
             << std::setw(14) << expectedCollisions(r.pairs, HASH_BITS)
             << std::setw(14) << expectedCollisions(setPairs, HASH_BITS) << std::fixed << "\n";
   }
   report << "\nExpected colliding pairs = (number of pairs) * 2^(-" << HASH_BITS << "); "
          << "a set of m distinct inputs has m(m-1)/2 pairs.\n\n";

   // 3: structured inputs
   std::cerr << "Structured inputs...\n";
   report << "=== Structured inputs ===\n\n";
   report << std::left << std::setw(24) << "Category" << std::right
          << std::setw(9) << "Inputs" << std::setw(10) << "Distinct" << std::setw(10) << "Hashes"
          << std::setw(12) << "Coll. grps" << std::setw(14) << "Coll. inputs" << "\n";
   report << std::string(79, '-') << "\n";

   std::ofstream structOut(outDir / "structured_collisions.txt");
   for (const auto& cat : buildCategories()) {
      std::vector<std::string> hashes = hashAll(cat.inputs);
      SetStats s = analyzeSet(cat.inputs, hashes);

      report << std::left << std::setw(24) << cat.name << std::right
             << std::setw(9) << s.total << std::setw(10) << s.distinctInputs << std::setw(10) << s.distinctHashes
             << std::setw(12) << s.groups.size() << std::setw(14) << s.collidingInputs << "\n";

      structOut << "== " << cat.name << ": " << cat.description << "\n";
      structOut << "   " << s.distinctInputs << " distinct inputs, " << s.distinctHashes << " distinct hashes, "
                << s.groups.size() << " collision groups\n";
      writeGroups(structOut, s, cat.inputs, hashes);
      structOut << "\n";
   }
   report << "\nCategory descriptions and collision examples: out/structured_collisions.txt\n";

   std::cerr << "Done. Results: " << (baseDir / "exp2_results.txt").string() << "\n";
   return 0;
}
