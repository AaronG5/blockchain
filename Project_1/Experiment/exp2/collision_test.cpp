struct RandomResult {
   int length;
   int pairs;
   std::size_t pairCollisions;
   SetStats full;
   std::uint64_t fullCollidingPairs;
   double seconds;
};

static RandomResult runRandom(int length, int pairs, const fs::path& outDir) {
   auto start = std::chrono::steady_clock::now();
   std::mt19937_64 rng(SEED + length);

   // inputs[2i] and inputs[2i + 1] form pair i
   std::vector<std::string> inputs;
   inputs.reserve(2 * static_cast<std::size_t>(pairs));
   for (int i = 0; i < pairs; ++i) {
      std::string a = randomString(rng, length);
      std::string b = randomString(rng, length);
      while (b == a) b = randomString(rng, length);
      inputs.push_back(std::move(a));
      inputs.push_back(std::move(b));
   }

   std::vector<std::string> hashes = hashAll(inputs);

   RandomResult r{length, pairs, 0, {}, 0, 0.0};
   std::ofstream pairOut(outDir / ("pair_collisions_" + std::to_string(length) + ".txt"));
   pairOut << "Pairwise collisions, length " << length << ", " << pairs << " pairs\n\n";
   for (int i = 0; i < pairs; ++i) {
      if (hashes[2 * i] == hashes[2 * i + 1]) {
         if (r.pairCollisions < MAX_SAVED_GROUPS) {
            pairOut << "Pair " << i << ": hash " << hashes[2 * i] << "\n"
                    << "   \"" << escape(inputs[2 * i]) << "\"\n"
                    << "   \"" << escape(inputs[2 * i + 1]) << "\"\n";
         }
         ++r.pairCollisions;
      }
   }
   if (r.pairCollisions == 0) pairOut << "No collisions found.\n";

   r.full = analyzeSet(inputs, hashes);
   r.fullCollidingPairs = collidingPairs(r.full);

   std::ofstream fullOut(outDir / ("set_collisions_" + std::to_string(length) + ".txt"));
   fullOut << "Full set collisions, length " << length << ", " << r.full.total << " inputs, "
           << r.full.distinctInputs << " distinct\n\n";
   writeGroups(fullOut, r.full, inputs, hashes);

   r.seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
   return r;
}

