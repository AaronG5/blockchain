// Collision resistance experiment.
//
// 1. Random pairs: for every length in LENGTHS, generates PAIRS pairs of random ASCII
//    strings (the two inputs of a pair always differ) and compares the hashes of each pair.
// 2. Full set: looks for repeated hashes among all inputs of one length, counting a
//    collision only when the inputs differ.
// 3. Structured inputs: small hand-made sets (permutations, repeated patterns, byte swaps, ...)
//    that target weaknesses random inputs are unlikely to hit.
//
// Usage (from Project_1, because the hash reads image.png from the working directory):
//    ./Experiment/exp2/collision_test [baseDir] [pairs]

