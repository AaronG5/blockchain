namespace fs = std::filesystem;

// Alphabet: the 95 printable ASCII characters, 0x20 (space) to 0x7E (~). One character is one byte.
static const std::string ALPHABET = [] {
   std::string s;
   for (int c = 0x20; c <= 0x7E; ++c) s += static_cast<char>(c);
   return s;
}();

// Random strings of length L are generated by std::mt19937_64 seeded with SEED + L,
// so every length can be reproduced on its own.
const std::uint64_t SEED = 20261007;
const std::vector<int> LENGTHS = {10, 100, 500, 1000};
const int DEFAULT_PAIRS = 100000;
const int HASH_BITS = 256;           // 64 hex characters
const int MAX_SAVED_GROUPS = 20;     // collision groups saved per length / category
const int MAX_SAVED_INPUTS = 5;      // inputs saved per collision group

// Unbiased index into the alphabet (rejection sampling, same result on every platform)
static std::size_t randomIndex(std::mt19937_64& rng, std::size_t n) {
   const std::uint64_t limit = std::numeric_limits<std::uint64_t>::max() - std::numeric_limits<std::uint64_t>::max() % n;
   std::uint64_t r;
   do {
      r = rng();
   } while (r >= limit);
   return r % n;
}

static std::string randomString(std::mt19937_64& rng, int length) {
   std::string s(length, ' ');
   for (char& c : s) c = ALPHABET[randomIndex(rng, ALPHABET.size())];
   return s;
}

// Makes inputs readable in the output files: printable ASCII as is, everything else as \xHH
static std::string escape(const std::string& s) {
   std::ostringstream out;
   for (unsigned char c : s) {
      if (c == '\\') {
         out << "\\\\";
      } else if (c >= 0x20 && c <= 0x7E) {
         out << c;
      } else {
         out << "\\x" << std::hex << std::setw(2) << std::setfill('0') << static_cast<int>(c) << std::dec;
      }
   }
   return out.str();
}

struct SetStats {
   std::size_t total = 0;
   std::size_t distinctInputs = 0;
   std::size_t distinctHashes = 0;
   std::size_t collidingInputs = 0;                // distinct inputs that share a hash with another distinct input
   std::vector<std::vector<std::size_t>> groups;   // indices of distinct inputs sharing one hash
};

// Groups distinct inputs by hash, keeping only groups with more than one distinct input
static SetStats analyzeSet(const std::vector<std::string>& inputs, const std::vector<std::string>& hashes) {
   SetStats stats;
   stats.total = inputs.size();

   std::unordered_map<std::string_view, std::size_t> seenInputs;
   std::unordered_map<std::string_view, std::vector<std::size_t>> byHash;
   seenInputs.reserve(inputs.size());
   byHash.reserve(inputs.size());

   for (std::size_t i = 0; i < inputs.size(); ++i) {
      if (!seenInputs.emplace(inputs[i], i).second) continue;
      byHash[hashes[i]].push_back(i);
   }

   stats.distinctInputs = seenInputs.size();
   stats.distinctHashes = byHash.size();
   for (auto& [hash, indices] : byHash) {
      if (indices.size() > 1) {
         stats.collidingInputs += indices.size();
         stats.groups.push_back(std::move(indices));
      }
   }
   // Biggest groups first, then by first index so the output is stable
   std::sort(stats.groups.begin(), stats.groups.end(), [](const auto& a, const auto& b) {
      if (a.size() != b.size()) return a.size() > b.size();
      return a.front() < b.front();
   });
   return stats;
}

// Number of colliding pairs inside the groups: sum of k(k-1)/2
static std::uint64_t collidingPairs(const SetStats& stats) {
   std::uint64_t pairs = 0;
   for (const auto& g : stats.groups) pairs += static_cast<std::uint64_t>(g.size()) * (g.size() - 1) / 2;
   return pairs;
}

// Expected number of colliding pairs for an ideal hash of `bits` bits: pairs * 2^(-bits)
static long double expectedCollisions(long double pairs, int bits) {
   return pairs * std::pow(2.0L, -bits);
}

static void writeGroups(std::ostream& out, const SetStats& stats, const std::vector<std::string>& inputs,
                        const std::vector<std::string>& hashes) {
   if (stats.groups.empty()) {
      out << "   No collisions found.\n";
      return;
   }
   int saved = 0;
   for (const auto& group : stats.groups) {
      if (saved++ == MAX_SAVED_GROUPS) {
         out << "   ... " << (stats.groups.size() - MAX_SAVED_GROUPS) << " more groups not shown\n";
         break;
      }
      out << "   Hash " << hashes[group.front()] << " (" << group.size() << " distinct inputs)\n";
      for (std::size_t k = 0; k < group.size() && k < MAX_SAVED_INPUTS; ++k) {
         const std::string& in = inputs[group[k]];
         out << "      [" << in.size() << " B] \"" << escape(in) << "\"\n";
      }
      if (group.size() > MAX_SAVED_INPUTS) {
         out << "      ... " << (group.size() - MAX_SAVED_INPUTS) << " more inputs\n";
      }
   }
}

static std::vector<std::string> hashAll(const std::vector<std::string>& inputs) {
   std::vector<std::string> hashes;
   hashes.reserve(inputs.size());
   for (const auto& in : inputs) hashes.push_back(hashFunction(in));
   return hashes;
}

