// Avalanche experiment.
//
// Generates PAIRS pairs split evenly between the lengths in LENGTHS. The second input of a
// pair is the first one with exactly one randomly chosen character replaced by a different
// character from the same alphabet (the length stays the same). For every pair the two hashes
// are compared bit by bit (after decoding the hex) and hex digit by hex digit.
//
// Usage (from Project_1, because the hash reads image.png from the working directory):
//    ./Experiment/exp2/avalanche_test [baseDir] [pairs]

#include <algorithm>
#include <bitset>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <limits>
#include <random>
#include <string>
#include <vector>

#include "../../hash.hpp"

namespace fs = std::filesystem;

// Alphabet: the 95 printable ASCII characters, 0x20 (space) to 0x7E (~). One character is one byte.
static const std::string ALPHABET = [] {
   std::string s;
   for (int c = 0x20; c <= 0x7E; ++c) s += static_cast<char>(c);
   return s;
}();

// Inputs of length L are generated by std::mt19937_64 seeded with SEED + L
const std::uint64_t SEED = 20261007;
const std::vector<int> LENGTHS = {10, 100, 500, 1000};
const int DEFAULT_PAIRS = 100000;
const int HASH_HEX = 64;
const int HASH_BITS = HASH_HEX * 4;

// Unbiased random number in [0, n) (rejection sampling, same result on every platform)
static std::size_t randomIndex(std::mt19937_64& rng, std::size_t n) {
   const std::uint64_t limit = std::numeric_limits<std::uint64_t>::max() - std::numeric_limits<std::uint64_t>::max() % n;
   std::uint64_t r;
   do {
      r = rng();
   } while (r >= limit);
   return r % n;
}

static std::string randomString(std::mt19937_64& rng, int length) {
   std::string s(length, ' ');
   for (char& c : s) c = ALPHABET[randomIndex(rng, ALPHABET.size())];
   return s;
}

static int hexValue(char c) {
   return (c <= '9') ? c - '0' : c - 'a' + 10;
}

// Decodes the hex strings to bytes and counts the bits that differ
static int bitDifference(const std::string& a, const std::string& b) {
   int bits = 0;
   for (int i = 0; i < HASH_HEX; i += 2) {
      int byteA = hexValue(a[i]) * 16 + hexValue(a[i + 1]);
      int byteB = hexValue(b[i]) * 16 + hexValue(b[i + 1]);
      bits += std::bitset<8>(byteA ^ byteB).count();
   }
   return bits;
}

static int hexDifference(const std::string& a, const std::string& b) {
   int digits = 0;
   for (int i = 0; i < HASH_HEX; ++i) {
      if (a[i] != b[i]) ++digits;
   }
   return digits;
}

struct Stats {
   int count = 0;
   double minimum = std::numeric_limits<double>::infinity();
   double maximum = 0.0;
   double total = 0.0;

   void add(double value) {
      ++count;
      minimum = std::min(minimum, value);
      maximum = std::max(maximum, value);
      total += value;
   }
   double average() const { return total / count; }
};

static void writeRow(std::ostream& out, const std::string& label, const Stats& bits, const Stats& hex) {
   out << std::left << std::setw(8) << label << std::right
       << std::setw(8) << bits.count
       << std::setw(10) << bits.minimum << std::setw(10) << bits.maximum << std::setw(10) << bits.average()
       << std::setw(10) << hex.minimum << std::setw(10) << hex.maximum << std::setw(10) << hex.average() << "\n";
}

int main(int argc, char* argv[]) {
   fs::path baseDir = (argc > 1) ? fs::path(argv[1]) : fs::absolute(argv[0]).lexically_normal().parent_path();
   int pairs = (argc > 2) ? std::stoi(argv[2]) : DEFAULT_PAIRS;
   int pairsPerLength = pairs / LENGTHS.size();
   fs::path outDir = baseDir / "out";
   fs::create_directories(outDir);

   // One row per pair, used for the histogram
   std::ofstream csv(outDir / "avalanche.csv");
   csv << "length,bit_diff_pct,hex_diff_pct\n";
   csv << std::setprecision(10);

   std::vector<Stats> bitStats(LENGTHS.size()), hexStats(LENGTHS.size());
   Stats bitTotal, hexTotal;

   for (std::size_t l = 0; l < LENGTHS.size(); ++l) {
      int length = LENGTHS[l];
      std::cerr << "Avalanche, length " << length << "...\n";
      std::mt19937_64 rng(SEED + length);

      for (int p = 0; p < pairsPerLength; ++p) {
         std::string a = randomString(rng, length);
         std::string b = a;

         // Replace one character with one of the other 94 alphabet characters
         std::size_t pos = randomIndex(rng, length);
         std::size_t oldIndex = ALPHABET.find(a[pos]);
         std::size_t newIndex = randomIndex(rng, ALPHABET.size() - 1);
         if (newIndex >= oldIndex) ++newIndex;
         b[pos] = ALPHABET[newIndex];

         std::string hashA = hashFunction(a);
         std::string hashB = hashFunction(b);

         double bitPct = 100.0 * bitDifference(hashA, hashB) / HASH_BITS;
         double hexPct = 100.0 * hexDifference(hashA, hashB) / HASH_HEX;

         bitStats[l].add(bitPct);
         hexStats[l].add(hexPct);
         bitTotal.add(bitPct);
         hexTotal.add(hexPct);
         csv << length << ',' << bitPct << ',' << hexPct << '\n';
      }
   }

   std::ofstream report(baseDir / "avalanche_results.txt");
   report << std::fixed << std::setprecision(2);
   report << "Alphabet: " << ALPHABET.size() << " printable ASCII characters, 0x20 (space) to 0x7E (~), 1 byte each\n";
   report << "Generator: std::mt19937_64, seed " << SEED << " + length\n";
   report << "Pairs: " << pairsPerLength * LENGTHS.size() << " (" << pairsPerLength << " per length), "
          << "each pair differs in exactly one character\n\n";

   report << std::left << std::setw(8) << "" << std::right << std::setw(8) << ""
          << std::setw(30) << "Bit difference (%)" << std::setw(30) << "Hex difference (%)" << "\n";
   report << std::left << std::setw(8) << "Length" << std::right << std::setw(8) << "Pairs"
          << std::setw(10) << "Min" << std::setw(10) << "Max" << std::setw(10) << "Avg"
          << std::setw(10) << "Min" << std::setw(10) << "Max" << std::setw(10) << "Avg" << "\n";
   report << std::string(76, '-') << "\n";
   for (std::size_t l = 0; l < LENGTHS.size(); ++l) {
      writeRow(report, std::to_string(LENGTHS[l]), bitStats[l], hexStats[l]);
   }
   report << std::string(76, '-') << "\n";
   writeRow(report, "All", bitTotal, hexTotal);

   report << "\nReference averages for independent, uniform outputs: 50% of bits, 93.75% of hex digits.\n";
   report << "Per-pair values for the histogram: out/avalanche.csv\n";

   std::cerr << "Done. Results: " << (baseDir / "avalanche_results.txt").string() << "\n";
   return 0;
}
